def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    digest.update(path.read_bytes())
    return digest.hexdigest()


def _is_lao(char: str) -> bool:
    return "\u0e80" <= char <= "\u0eff"


def _render_line(
    image: Image.Image,
    text: str,
    position: tuple[int, int],
    lao_font_path: Path,
    latin_font_path: Path,
) -> None:
    x, y = position
    for use_lao, chars in groupby(text, key=_is_lao):
        run = "".join(chars)
        font_path = lao_font_path if use_lao else latin_font_path
        rendered = shaped_text_image(font_path, 58, run)
        image.paste(rendered, (x, y), rendered)
        x += rendered.width

def _render(
    text: str,
    lao_font_path: Path,
    latin_font_path: Path,
    noisy: bool,
) -> Image.Image:
    image = Image.new("RGB", (1800, 520), "white")

    y = 100
    for line in text.splitlines():
        _render_line(
            image,
            line,
            (90, y),
            lao_font_path,
            latin_font_path,
        )
        y += 100

    if not noisy:
        return image

    rng = np.random.default_rng(20260921)
    array = np.asarray(image.convert("L"), dtype=np.int16)
    noise = rng.normal(0, 7, size=array.shape)
    array = np.clip(array + noise, 0, 255).astype(np.uint8)
    noisy_image = Image.fromarray(array)
    return noisy_image.filter(ImageFilter.GaussianBlur(radius=0.6)).convert("RGB")


def generate(output: Path, lao_font_path: Path, latin_font_path: Path) -> Path:
    if not lao_font_path.is_file():
        raise FileNotFoundError(f"Lao font not found: {lao_font_path}")
    if not latin_font_path.is_file():
        raise FileNotFoundError(f"Latin font not found: {latin_font_path}")

    data_dir = output / "data"
    truth_dir = output / "ground-truth"
    data_dir.mkdir(parents=True, exist_ok=True)
    truth_dir.mkdir(parents=True, exist_ok=True)

    manifest_path = output / "manifest.jsonl"
    entries: list[str] = []

    for sample in SAMPLES:
        image_path = data_dir / f"{sample['id']}.png"
        truth_path = truth_dir / f"{sample['id']}.txt"

        image = _render(
            sample["text"],
            lao_font_path,
            latin_font_path,
            bool(sample["noise"]),
        )
        image.save(image_path, format="PNG", optimize=True)
        truth_path.write_text(sample["text"] + "\n", encoding="utf-8")

        entry = {
            "id": sample["id"],
            "document_id": sample["document_id"],
            "split": "test",
            "subset": sample["subset"],
            "source": str(image_path.relative_to(output)),
            "ground_truth": str(truth_path.relative_to(output)),
            "language": "lo+en" if sample["subset"] == "mixed-lao-english" else "lo",
            "license": "CC0-1.0",
            "provenance": "Deterministic synthetic smoke fixture generated by this repository.",
            "sha256": _sha256(image_path),
            "notes": (
                "Synthetic pipeline smoke test; not part of the real-document accuracy "
                "benchmark."
            ),
        }
        entries.append(json.dumps(entry, ensure_ascii=False))

    manifest_path.write_text("\n".join(entries) + "\n", encoding="utf-8")
    return manifest_path


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate deterministic Lao OCR smoke fixtures.")
    parser.add_argument("--output", type=Path, default=Path("benchmarks/generated/smoke"))
    parser.add_argument("--lao-font", type=Path, default=Path(DEFAULT_LAO_FONT))
    parser.add_argument("--latin-font", type=Path, default=Path(DEFAULT_LATIN_FONT))
    args = parser.parse_args()

    manifest = generate(args.output, args.lao_font, args.latin_font)
    print(manifest)
    return 0


